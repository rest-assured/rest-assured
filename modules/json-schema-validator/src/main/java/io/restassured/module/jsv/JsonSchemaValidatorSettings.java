package io.restassured.module.jsv;

import com.github.fge.jsonschema.main.JsonSchemaFactory;

/**
 * Settings for the {@link JsonSchemaValidator}.
 * <p>
 * The {@link JsonSchemaFactory} and {@link #checkedValidation(boolean) checked validation} settings only apply to the java-json-tools
 * json-schema-validator, which is optional. See {@link JsonSchemaVersion} for which schemas it validates.
 * </p>
 */
public class JsonSchemaValidatorSettings {
    /**
     * Created on first use when not given, so that the default settings don't need java-json-tools
     */
    private volatile JsonSchemaFactory jsonSchemaFactory;
    private boolean checkedValidation;
    private boolean parseUriAndUrlsAsJsonNode;
    private JsonSchemaVersion schemaVersion;

    private JsonSchemaValidatorSettings(JsonSchemaFactory jsonSchemaFactory, boolean checkedValidation, boolean parseUriAndUrlsAsJsonNode, JsonSchemaVersion schemaVersion) {
        this.jsonSchemaFactory = jsonSchemaFactory;
        this.checkedValidation = checkedValidation;
        this.parseUriAndUrlsAsJsonNode = parseUriAndUrlsAsJsonNode;
        this.schemaVersion = schemaVersion;
    }

    /**
     * Initializes JsonSchemaValidatorSettings with a specific {@link JsonSchemaFactory} and checked validation.
     * It will also use checked validation and treating uri's and url's as Strings. To change the latter refer to {@link #parseUriAndUrlsAsJsonNode(boolean)}.
     */
    public JsonSchemaValidatorSettings(JsonSchemaFactory jsonSchemaFactory, boolean checkedValidation) {
        this(notNull(jsonSchemaFactory), checkedValidation, false, null);
    }

    /**
     * Initializes JsonSchemaValidatorSettings with a specific {@link JsonSchemaFactory}. The settings will also use checked validation and treating uri's and url's as Strings.
     */
    public JsonSchemaValidatorSettings(JsonSchemaFactory jsonSchemaFactory) {
        this(jsonSchemaFactory, true);
    }

    /**
     * Initializes JsonSchemaValidatorSettings with a default {@link JsonSchemaFactory} (generated by <code>JsonSchemaFactory.byDefault()</code>
     * when it's first used) and using checked validation and treating uri's and url's as Strings.
     */
    public JsonSchemaValidatorSettings() {
        this(null, true, false, null);
    }

    /**
     * @return The {@link JsonSchemaFactory} to use
     * @throws JsonSchemaValidationException If no factory was given and java-json-tools isn't on the classpath
     */
    public JsonSchemaFactory jsonSchemaFactory() {
        JsonSchemaFactory factory = jsonSchemaFactory;
        if (factory == null) {
            if (!JsonSchemaValidator.JAVA_JSON_TOOLS_AVAILABLE) {
                throw JsonSchemaValidator.javaJsonToolsRequired("A JsonSchemaFactory");
            }
            factory = JavaJsonToolsSchemaValidation.defaultJsonSchemaFactory();
            jsonSchemaFactory = factory;
        }
        return factory;
    }

    public boolean shouldParseUriAndUrlsAsJsonNode() {
        return parseUriAndUrlsAsJsonNode;
    }

    public boolean shouldUseCheckedValidation() {
        return checkedValidation;
    }

    /**
     * @return The {@link JsonSchemaVersion} used for schemas without <code>$schema</code>, or <code>null</code> if not configured (draft-04 is then used).
     */
    public JsonSchemaVersion schemaVersion() {
        return schemaVersion;
    }

    /**
     * Instruct the JsonSchemaValidator which JSON Schema version (draft) to use for schemas that don't declare <code>$schema</code>
     * (or declare an unknown <code>$schema</code>). A <code>$schema</code> declared by the schema always takes precedence.
     * By default (<code>null</code>) such schemas are validated as draft-04. See {@link JsonSchemaVersion} for details.
     *
     * @param schemaVersion The JSON Schema version to use for schemas without <code>$schema</code>, or <code>null</code> for the default (draft-04).
     * @return A new instance of JsonSchemaValidatorSettings
     */
    public JsonSchemaValidatorSettings schemaVersion(JsonSchemaVersion schemaVersion) {
        return new JsonSchemaValidatorSettings(jsonSchemaFactory, checkedValidation, parseUriAndUrlsAsJsonNode, schemaVersion);
    }

    /**
     * Instruct the java-json-tools json-schema-validator to use checked validation or not. The networknt json-schema-validator ignores it.
     *
     * @param shouldUseCheckedValidation <code>true</code> to use checked validation, <code>false</code> otherwise.
     * @return A new instance of JsonSchemaValidatorSettings
     */
    public JsonSchemaValidatorSettings checkedValidation(boolean shouldUseCheckedValidation) {
        return new JsonSchemaValidatorSettings(jsonSchemaFactory, shouldUseCheckedValidation, parseUriAndUrlsAsJsonNode, schemaVersion);
    }

    /**
     * Instruct the java-json-tools json-schema-validator to validate with a schema given as a URL or URI parsed as JSON (<code>true</code>),
     * or to load the schema from the URL itself (<code>false</code>), which lets it resolve relative <code>$ref</code>'s against the URL.
     * The networknt json-schema-validator always resolves them against the URL.
     * <p>
     * Default is <code>false</code>.
     * </p>
     *
     * @param parseUriAndUrlsAsJsonNode <code>true</code> to parse URI's and URL's as JSON, <code>false</code> otherwise.
     * @return A new instance of JsonSchemaValidatorSettings
     */
    public JsonSchemaValidatorSettings parseUriAndUrlsAsJsonNode(boolean parseUriAndUrlsAsJsonNode) {
        return new JsonSchemaValidatorSettings(jsonSchemaFactory, checkedValidation, parseUriAndUrlsAsJsonNode, schemaVersion);
    }

    /**
     * Set a {@link JsonSchemaFactory} instance that the java-json-tools json-schema-validator will use.
     *
     * @param jsonSchemaFactory The {@link JsonSchemaFactory} instance to use.
     * @return A new instance of JsonSchemaValidatorSettings
     */
    public JsonSchemaValidatorSettings jsonSchemaFactory(JsonSchemaFactory jsonSchemaFactory) {
        return new JsonSchemaValidatorSettings(notNull(jsonSchemaFactory), checkedValidation, parseUriAndUrlsAsJsonNode, schemaVersion);
    }

    /**
     * Syntactic sugar.
     *
     * @return The same settings instance.
     */
    public JsonSchemaValidatorSettings and() {
        return this;
    }

    /**
     * Syntactic sugar.
     *
     * @return The same settings instance.
     */
    public JsonSchemaValidatorSettings with() {
        return this;
    }

    /**
     * Create a new instance of {@link JsonSchemaValidatorSettings}. Same as calling {@link #JsonSchemaValidatorSettings()}.
     *
     * @return A default instance of the {@link JsonSchemaValidatorSettings}.
     */
    public static JsonSchemaValidatorSettings settings() {
        return new JsonSchemaValidatorSettings();
    }

    private static JsonSchemaFactory notNull(JsonSchemaFactory jsonSchemaFactory) {
        if (jsonSchemaFactory == null) {
            throw new IllegalArgumentException("JsonSchemaFactory cannot be null");
        }
        return jsonSchemaFactory;
    }
}
